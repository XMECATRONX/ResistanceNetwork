//! rstn-crypto -- Post-Quantum Cryptography
//!
//! All cryptographic primitives for Resistance Network (RSTN).
//! Every algorithm here must resist both Shor's and Grover's attacks.
//!
//! Active primitives:
//! - Keccak-512 (hash, 256-bit quantum security via Grover resistance)
//! - Dilithium3 (signatures, NIST FIPS 204, Category 2)
//! - PQ-VRF (leader election, Dilithium-based)
//! - PQ-noise (transport encryption, Kyber KEM + Dilithium)
//! - Hybrid signatures (Dilithium3 + Ed25519, dual verification)
//! - SPHINCS+ / SLH-DSA (FIPS 205, hash-based fallback)
//! - Stealth addresses (Kyber768 KEM, one-time addresses)
//! - Forward security (epoch-based key rotation, anti long-range)
//! - Quantum alarm (emergency key rotation on cryptographic break)
//! - Account abstraction (multi-sig, social recovery, scheme rotation)

