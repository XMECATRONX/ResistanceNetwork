//! rstn-core -- BFT Consensus Engine
//!
//! HotStuff-inspired BFT consensus with DAG data availability.
//! Two-round finality: PREPARE -> COMMIT -> FINALIZE.
//! Target: 0.4s block time, deterministic finality in 2 rounds.
//!
//! Forward security (anti long-range attack): the engine carries a
//! `ForwardSecurityLedger` that records which validator pubkeys are
//! authorized for each epoch. When a node syncs from genesis, every block's
//! signer is checked against the ledger for that block's epoch. An attacker
//! who buys a retired epoch key cannot sign blocks in a later epoch — the
//! key is not in the authorized set.

use crate::{
    Block, BlockHeader, BftVote, BftVotePhase, ConsensusState, CoreError,
    ValidatorStatus, Transaction,
    EPOCH_LENGTH,
};
use crate::forward_security::ForwardSecurityLedger;
use rstn_crypto::{Dilithium3Keypair, Dilithium3Signature, Dilithium3PublicKey, keccak512, SIG_SIZE, VrfKeypair, VrfOutput, VrfProof, verify_vrf};
use std::collections::HashMap;

/// BFT phases in order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum BftPhase {
    /// Leader broadcasts a proposal.
    Propose,
    /// Validators sign the proposal (round 1).
    Prepare,
    /// Validators sign the prepare certificate (round 2).
    Commit,
    /// Block is finalized and appended to chain.
    Finalize,
}

/// The consensus engine drives block production.
pub struct ConsensusEngine {
    /// Shared consensus state (validators, chain, votes).
    pub state: ConsensusState,
    /// This node's keypair for signing votes and proposals.
    pub keypair: Dilithium3Keypair,
    /// Current phase in the BFT round.
    pub phase: BftPhase,
    /// Prepare certificates: block_hash -> votes collected.
    pub prepare_votes: HashMap<[u8; 64], Vec<BftVote>>,
    /// Commit certificates: block_hash -> votes collected.
    pub commit_votes: HashMap<[u8; 64], Vec<BftVote>>,
    /// Mempool of pending transactions.
    pub mempool: Vec<Transaction>,
    /// Account-state lookup for nonce validation (#2). Set by the runner.
    pub account_nonce_fn: Option<Box<dyn Fn(&[u8; 20]) -> Option<u64> + Send + Sync>>,
    /// Account-state lookup for balance validation (#2). Set by the runner.
    pub account_balance_fn: Option<Box<dyn Fn(&[u8; 20]) -> Option<u128> + Send + Sync>>,
    /// Validators detected equivocating (double-signing two different blocks
    /// at the same height+phase). A Vec (not a single slot) so that if two
    /// validators equivocate simultaneously, the second does NOT overwrite the
    /// first -- both are recorded and both get slashed (P2). The runner reads
    /// this each tick and persists the slash to the DB so it survives a node
    /// restart (P1).
    pub last_equivocators: Vec<(Dilithium3PublicKey, u64)>,
    /// Forward-security ledger: records which validator pubkeys are authorized
    /// for which epochs. Seeded at genesis with the initial validator set, and
    /// extended as validators rotate their keys each epoch. A node syncing
    /// from genesis validates every block's signer against this ledger for
    /// the block's epoch, rejecting blocks signed by retired epoch keys
    /// (anti long-range attack). Disabled by default (None) to preserve
    /// testnet compatibility; the runner enables it on production nodes.
    pub forward_security: Option<ForwardSecurityLedger>,
    /// G14 — Forced-inclusion pool. A tx becomes "forced" when 2/3+ of the
    /// active validator set attests it was excluded from block N. The
    /// proposer of block N+1 MUST include all forced txs (up to the gas
    /// budget) or the block is invalid — censorship of a forced tx is a
    /// protocol violation. This makes the claim "any transaction can be
    /// forced into the block at N+1 if it was censored at N" true.
    pub forced_pool: crate::forced_inclusion::ForcedInclusionPool,
    /// G13 — Threshold-encrypted mempool. When enabled, the proposer sees
    /// only the commitment (hash) of each tx, not the payload. The payload
    /// is decrypted only after finality (2/3+ COMMIT), making MEV
    /// structurally impossible. The threshold key is generated by the
    /// committee setup; the runner enables this on production nodes.
    pub threshold_mempool: Option<crate::threshold_mempool::ThresholdKey>,
    /// G13 — Encrypted txs awaiting post-finality decryption. Each entry
    /// is a threshold-encrypted ciphertext + the commitment. After the block
    /// is finalized, the committee produces decryption shares and the
    /// plaintext is recovered — only then is the tx's payload known.
    pub encrypted_txs: Vec<crate::threshold_mempool::ThresholdCiphertext>,
    /// On-chain circuit breakers (G15-exec). Detects anomalous value drain
    /// and oracle deviation, and gates transfers/oracle-ops. The runner
    /// feeds every transfer through `record_outflow` and checks `is_paused`
    /// before executing. This makes the "circuit breakers on-chain" claim
    /// true at runtime, not just in a standalone module.
    pub circuit_breaker: crate::circuit_breaker::CircuitBreaker,
    /// Quantum alarm (G15-alarm). Detects a classically-impossible forgery
    /// and, on 2/3+ validator cosignature, transitions to Emergency —
    /// after which Dilithium3-only signatures are rejected. The runner
    /// checks `is_emergency()` at finalization to enforce the fallback.
    pub quantum_alarm: crate::quantum_alarm::QuantumAlarm,
    /// EIP-1559 fee market v3 (base fee burned + tip to validator + dynamic
    /// inflation). The runner calls `fee_market.split_fee()` for each tx to
    /// compute the burn (base fee) and the validator tip — two SEPARATE
    /// streams that do not compete (fixes Solana's error). The base fee is
    /// floored at 1 gwei so the burn never dies at scale (fixes Ethereum's
    /// error). `update_after_block()` is called after each block to adjust.
    pub fee_market: crate::fee_market::FeeMarket,
    /// Dynamic inflation targeting 66% staked, capped at 2% (fixes Cosmos'
    /// 20% dilution). The runner feeds the current staking ratio and the
    /// multiplier adjusts the reserve distribution schedule.
    pub dynamic_inflation: crate::fee_market::DynamicInflation,
}

impl ConsensusEngine {
    pub fn new(state: ConsensusState, keypair: Dilithium3Keypair) -> Self {
        Self {
            state,
            keypair,
            phase: BftPhase::Propose,
            prepare_votes: HashMap::new(),
            commit_votes: HashMap::new(),
            mempool: Vec::new(),
            account_nonce_fn: None,
            account_balance_fn: None,
            last_equivocators: Vec::new(),
            forward_security: None,
            forced_pool: crate::forced_inclusion::ForcedInclusionPool::new(),
            threshold_mempool: None,
            encrypted_txs: Vec::new(),
            circuit_breaker: crate::circuit_breaker::CircuitBreaker::new(),
            quantum_alarm: crate::quantum_alarm::QuantumAlarm::new(),
            fee_market: crate::fee_market::FeeMarket::new(),
            dynamic_inflation: crate::fee_market::DynamicInflation::new(),
        }
    }

    /// EIP-1559 v3 — Returns the current base fee (floored at 1 gwei) for
    /// RPC display and wallet fee estimation.
    pub fn current_base_fee(&self) -> u128 {
        self.fee_market.current_base_fee()
    }

    /// EIP-1559 v3 — Split a tx's fee into burn (base fee, 100% destroyed)
    /// and tip (100% to validator). Streams are independent — the burn does
    /// not reduce the validator's tip (fixes Solana's error).
    pub fn split_tx_fee(&self, gas_price: u128, gas_limit: u64) -> (u128, u128) {
        self.fee_market.split_fee(gas_price, gas_limit)
    }

    /// Dynamic inflation v3 — Compute the reserve distribution multiplier
    /// for the current staking ratio. Targets 66% staked, capped at +2%
    /// (fixes Cosmos' 20% dilution). Returns basis points (10000 = 1.0×).
    pub fn inflation_multiplier(&self, staking_ratio_bps: u128) -> u128 {
        self.dynamic_inflation.rate_multiplier(staking_ratio_bps)
    }

    /// G14 — Enable the forced-inclusion pool with the current validator set.
    /// The threshold is 2/3+ of the active validator count, matching BFT.
    pub fn enable_forced_inclusion(&mut self) {
        // The pool is always present; this is a no-op marker for the runner
        // to know the feature is active. The threshold is computed on-demand
        // from the active validator count.
    }

    /// G14 — Attest that a tx was excluded from block N. Called by a
    /// validator when it detects a tx in the mempool was not included in
    /// the finalized block N. When 2/3+ of the active set attest, the tx
    /// becomes "forced" and the next proposer MUST include it.
    pub fn attest_excluded(
        &mut self,
        attestation: crate::forced_inclusion::InclusionAttestation,
        tx_payload: Vec<u8>,
    ) -> bool {
        let active_count = self
            .state
            .validators
            .iter()
            .filter(|v| v.status == ValidatorStatus::Active)
            .count();
        if active_count == 0 {
            return false;
        }
        let threshold = active_count * 2 / 3 + 1;
        let validator_set: Vec<Dilithium3PublicKey> = self
            .state
            .validators
            .iter()
            .filter(|v| v.status == ValidatorStatus::Active)
            .map(|v| v.pubkey.clone())
            .collect();
        self.forced_pool
            .attest_excluded(attestation, tx_payload, &validator_set, threshold)
    }

    /// G14 — Validate that a proposed block includes all forced txs that
    /// fit in the gas budget. Called by validators in `vote_prepare` to
    /// reject a block that censors a forced tx.
    pub fn validate_forced_inclusion(
        &self,
        block: &Block,
        gas_budget: u64,
        gas_per_tx: u64,
    ) -> Result<(), CoreError> {
        use std::collections::HashSet;
        let included: HashSet<crate::forced_inclusion::TxCommitment> = block
            .transactions
            .iter()
            .map(|tx| {
                let enc = tx.canonical_encode();
                let mut commit = [0u8; 64];
                commit.copy_from_slice(&keccak512(&enc));
                commit
            })
            .collect();
        self.forced_pool
            .validate_block(&included, gas_budget, gas_per_tx)
            .map_err(|e| CoreError::InvalidBlock(format!("forced-inclusion violation: {:?}", e)))
    }

    /// G13 — Enable the threshold-encrypted mempool. The committee key is
    /// generated from the active validator set with a deterministic seed.
    /// All validators generate the same key (same seed + same set), so the
    /// committee can decrypt collectively after finality.
    pub fn enable_threshold_mempool(&mut self) {
        let active_count = self
            .state
            .validators
            .iter()
            .filter(|v| v.status == ValidatorStatus::Active)
            .count();
        if active_count == 0 {
            return;
        }
        // Deterministic seed from the validator set so all nodes derive the
        // same committee key (production would use a DKG; here the committee
        // reproduces the key from the known validator set).
        let seed = {
            let mut h = [0u8; 32];
            for v in self.state.validators.iter() {
                for b in 0..32 {
                    h[b] ^= v.pubkey.0[b % v.pubkey.0.len()];
                }
            }
            let kh = keccak512(&h);
            u64::from_le_bytes(kh[..8].try_into().unwrap_or([0u8; 8]))
        };
        self.threshold_mempool = Some(crate::threshold_mempool::ThresholdKey::generate(active_count, seed));
    }

    /// G13 — Encrypt a tx payload under the threshold key. Called by the
    /// runner/wallet before broadcasting a tx to the mempool when the
    /// threshold mempool is enabled. The proposer sees only the commitment.
    pub fn encrypt_tx(&self, payload: &[u8]) -> Option<crate::threshold_mempool::ThresholdCiphertext> {
        self.threshold_mempool
            .as_ref()
            .map(|key| crate::threshold_mempool::encrypt_tx(key, payload))
    }

    /// G13 — Combine decryption shares to recover a tx payload after
    /// finality. Called by the runner after the block is finalized and the
    /// committee has produced their shares.
    pub fn decrypt_tx(
        &self,
        ct: &crate::threshold_mempool::ThresholdCiphertext,
        shares: &[crate::threshold_mempool::DecryptionShare],
    ) -> Result<Vec<u8>, CoreError> {
        let key = self
            .threshold_mempool
            .as_ref()
            .ok_or(CoreError::Consensus("threshold mempool not enabled".into()))?;
        crate::threshold_mempool::combine_shares(key, ct, shares)
            .map_err(|e| CoreError::InvalidTransaction(format!("threshold decryption failed: {:?}", e)))
    }

    /// Detect equivocation: has `voter` already signed a *different* block
    /// at the same `height` in the same `phase`? If so, this is double-signing
    /// (equivocation) -- a Byzantine fault. The offender is slashed 5% of
    /// stake (proportional, per the slashing table) and the vote is rejected.
    /// Returns true if equivocation was detected (caller should reject the vote).
    fn detect_and_slash_equivocation(
        &mut self,
        voter: &Dilithium3PublicKey,
        height: u64,
        block_hash: &[u8; 64],
        phase: BftVotePhase,
    ) -> bool {
        let store = if phase == BftVotePhase::Prepare {
            &self.prepare_votes
        } else {
            &self.commit_votes
        };
        // Scan every block_hash bucket for a vote from `voter` at `height`
        // on a DIFFERENT block. A vote on the same block is a duplicate
        // (handled by the caller's dedup), not equivocation.
        for (hash, votes) in store.iter() {
            if hash == block_hash {
                continue;
            }
            for v in votes.iter() {
                if v.height == height && v.voter.0 == voter.0 {
                    // Equivocation detected: voter signed block `hash` AND
                    // is now signing `block_hash` at the same height+phase.
                    tracing::warn!(
                        "EQUIVOCATION: validator {:?} double-signed at height {} \
                         (block A={}.., block B={}..) -- slashing 5%",
                        &voter.0[..8], height,
                        hex::encode(&hash[..8]),
                        hex::encode(&block_hash[..8]),
                    );
                    // Proportional slash: 5% of stake (equivocation rate).
                    let _ = self.state.slash_validator(voter, 5);
                    // Record in the Vec (P2): multiple simultaneous equivocators
                    // are all recorded, none overwrites another.
                    self.last_equivocators.push((voter.clone(), height));
                    return true;
                }
            }
        }
        false
    }

    /// Add a transaction to the mempool.
    /// Verifies the Dilithium3 signature before accepting the transaction.
    /// Checks for duplicate nonces (replay protection) AND validates the nonce
    /// against the account state (#2): a tx whose nonce does not match the
    /// account's expected nonce (or a small future gap) is rejected, and the
    /// sender must have enough balance to cover value + gas.
    /// Anti-spam (#7): the mempool enforces a per-sender cap (max 64 pending
    /// txs per sender) and a global cap (max 4096 txs). This prevents a dust
    /// attack from saturating the mempool and starving legitimate users.
    /// Invalid transactions are rejected -- they never enter the mempool.
    pub fn add_tx(&mut self, tx: Transaction) -> Result<(), CoreError> {
        // Verify the transaction signature
        tx.verify_signature()?;

        let sender_addr = rstn_crypto::derive_address(&tx.from);

        // Anti-spam (#7): global mempool cap. If the pool is full, reject
        // new txs rather than growing unboundedly. Legitimate txs already
        // in the pool are not evicted.
        const MAX_MEMPOOL_TXS: usize = 4096;
        if self.mempool.len() >= MAX_MEMPOOL_TXS {
            return Err(CoreError::InvalidTransaction(format!(
                "mempool full ({} txs) -- retry later", MAX_MEMPOOL_TXS
            )));
        }

        // Anti-spam (#7): per-sender cap. A single sender cannot occupy more
        // than MAX_TXS_PER_SENDER slots, preventing a dust attack from one
        // account saturating the pool.
        const MAX_TXS_PER_SENDER: usize = 64;
        let sender_count = self.mempool.iter().filter(|t| {
            rstn_crypto::derive_address(&t.from) == sender_addr
        }).count();
        if sender_count >= MAX_TXS_PER_SENDER {
            return Err(CoreError::InvalidTransaction(format!(
                "sender has too many pending txs ({}) -- limit {}", sender_count, MAX_TXS_PER_SENDER
            )));
        }

        // Replay protection: reject if a tx with the same sender + nonce
        // is already in the mempool.
        let duplicate = self.mempool.iter().any(|t| {
            let t_addr = rstn_crypto::derive_address(&t.from);
            t_addr == sender_addr && t.nonce == tx.nonce
        });
        if duplicate {
            return Err(CoreError::InvalidTransaction(format!(
                "duplicate tx: sender already has nonce {} in mempool", tx.nonce
            )));
        }

        // Nonce + balance validation against account state (#2).
        // The caller injects the current account state via `account_nonce`
        // and `account_balance` on the ConsensusEngine (set by the runner
        // before adding a tx). Without this, the mempool would accept txs
        // with nonces already consumed on-chain (replay-after-mempool-flush)
        // or with insufficient balance.
        if let Some(expected) = self.account_nonce(&sender_addr) {
            const MAX_GAP: u64 = 16; // allow a small future nonce window
            if tx.nonce < expected {
                return Err(CoreError::InvalidTransaction(format!(
                    "nonce too low: expected >= {}, got {}", expected, tx.nonce
                )));
            }
            if tx.nonce > expected + MAX_GAP {
                return Err(CoreError::InvalidTransaction(format!(
                    "nonce gap too large: expected ~{}, got {} (max gap {})", expected, tx.nonce, MAX_GAP
                )));
            }
        }
        if let Some(balance) = self.account_balance(&sender_addr) {
            let needed = tx.value.saturating_add(tx.gas_price.saturating_mul(tx.gas_limit as u128));
            if balance < needed {
                return Err(CoreError::InvalidTransaction(format!(
                    "insufficient balance: have {}, need {} (value + gas)", balance, needed
                )));
            }
        }

        self.mempool.push(tx);
        Ok(())
    }

    /// Inject the account-state lookup callbacks used by `add_tx` to validate
    /// nonce and balance against on-chain state. The runner sets these to read
    /// from the storage layer; absent that, validation is skipped (test-only).
    pub fn set_account_lookup(
        &mut self,
        nonce_fn: impl Fn(&[u8; 20]) -> Option<u64> + Send + Sync + 'static,
        balance_fn: impl Fn(&[u8; 20]) -> Option<u128> + Send + Sync + 'static,
    ) {
        self.account_nonce_fn = Some(Box::new(nonce_fn));
        self.account_balance_fn = Some(Box::new(balance_fn));
    }

    fn account_nonce(&self, addr: &[u8; 20]) -> Option<u64> {
        self.account_nonce_fn.as_ref().and_then(|f| f(addr))
    }
    fn account_balance(&self, addr: &[u8; 20]) -> Option<u128> {
        self.account_balance_fn.as_ref().and_then(|f| f(addr))
    }

    /// Enable forward security and seed the ledger with the current validator
    /// set for epoch 0. Called by the runner on production nodes (or testnets
    /// that want to exercise the anti long-range path). Once enabled, the
    /// engine validates every accepted block's signer against the ledger.
    pub fn enable_forward_security(&mut self) {
        let mut ledger = ForwardSecurityLedger::new();
        ledger.seed_genesis(&self.state.validators);
        self.forward_security = Some(ledger);
    }

    /// Returns true if forward security is active (the ledger is present).
    pub fn has_forward_security(&self) -> bool {
        self.forward_security.is_some()
    }

    /// Validate that a block's signer was authorized for the block's epoch,
    /// using the forward-security ledger. This is the anti long-range check:
    /// an attacker who buys a retired epoch key cannot sign blocks in a
    /// later epoch because the key is not in the authorized set. No-op when
    /// forward security is disabled (testnet compatibility).
    pub fn validate_forward_security(
        &self,
        epoch: u64,
        signer: &Dilithium3PublicKey,
    ) -> Result<(), CoreError> {
        if let Some(ledger) = &self.forward_security {
            ledger.validate_block_signer(epoch, &signer.0)?;
        }
        Ok(())
    }

    /// Leader proposes a new block by bundling mempool transactions.
    /// `state_root` is computed by the caller from the storage layer
    /// (rstn-storage), avoiding a circular dependency on rstn-core.
    ///
    /// G14 — Forced-inclusion: the proposer MUST drain forced txs from the
    /// forced-inclusion pool BEFORE taking regular mempool txs. If the
    /// proposer skips a forced tx that fits in the gas budget, the block is
    /// invalid and the committee rejects it — censorship of a forced tx is
    /// a protocol violation.
    pub fn propose_block(&mut self, state_root: [u8; 64]) -> Result<Block, CoreError> {
        let leader = self
            .state
            .select_leader()
            .ok_or_else(|| CoreError::Consensus("no active validators".into()))?;

        // Only the elected leader proposes
        if leader.pubkey.0 != self.keypair.public.0 {
            return Err(CoreError::Consensus(
                "not the elected leader for this round".into(),
            ));
        }

        let parent = self
            .state
            .latest_block()
            .ok_or_else(|| CoreError::Consensus("no genesis block".into()))?;

        // G14: forced-inclusion txs MUST be included first. The proposer
        // takes them from the forced pool up to the gas budget, then fills
        // the rest of the block with regular mempool txs. If the proposer
        // refuses, the block is invalid (checked by validate_forced_inclusion
        // in vote_prepare).
        let gas_per_tx: u64 = 21_000;
        let block_gas_budget: u64 = 30_000_000; // 30M gas per block
        let forced_payloads = self.forced_pool.take_forced(block_gas_budget, gas_per_tx);

        // Deserialize forced tx payloads back into Transaction objects.
        let mut txs: Vec<Transaction> = forced_payloads
            .into_iter()
            .filter_map(|payload| serde_json::from_slice::<Transaction>(&payload).ok())
            .collect();

        // Fill the rest of the block with regular mempool txs.
        let remaining_budget = block_gas_budget.saturating_sub(txs.len() as u64 * gas_per_tx);
        let max_regular = (remaining_budget / gas_per_tx) as usize;
        let regular: Vec<Transaction> = self
            .mempool
            .drain(..self.mempool.len().min(512.min(max_regular.max(1))))
            .collect();
        txs.extend(regular);

        // Compute tx_root
        let tx_root = compute_merkle_root(&txs);

        // G3 — DAS: compute the data-availability root over the erasure-coded
        // block body. Light clients sample shards against this root, so a
        // proposer who withholds data is caught with overwhelming odds.
        let body_bytes = serde_json::to_vec(&txs).unwrap_or_default();
        let das_blob = crate::das::encode_block_body(&body_bytes, 256, 4);
        let data_root = das_blob.root;

        // PQ-VRF leader election: evaluate VRF(secret, parent_hash || height)
        // and commit the output + proof to the block header. The VRF output
        // determines the leader for the NEXT block (chain-VRF, Algorand-style).
        let vrf_kp = VrfKeypair::from_dilithium(&self.keypair);
        let mut vrf_input = parent.hash().to_vec();
        vrf_input.extend_from_slice(&(parent.header.height + 1).to_le_bytes());
        let (vrf_output, vrf_proof) = vrf_kp.evaluate(&vrf_input);

        let header = BlockHeader {
            height: parent.header.height + 1,
            parent_hash: parent.hash(),
            state_root, // Real state root from storage layer
            tx_root,
            timestamp: current_timestamp(),
            validator: self.keypair.public.clone(),
            signature: Dilithium3Signature([0u8; SIG_SIZE]), // filled after signing
            shard_id: 0,
            epoch: (parent.header.height + 1) / EPOCH_LENGTH,
            round: self.state.current_round,
            data_root,
            vrf_output: vrf_output.0,
            vrf_proof: Dilithium3Signature(vrf_proof.0),
        };

        let mut block = Block {
            header,
            transactions: txs,
        };

        // EIP-1559 v3: compute the total gas used by this block and split
        // each tx's fee into burn (base fee) + tip (validator). The burn is
        // 100% destroyed; the tip goes 100% to the block's validator. These
        // are SEPARATE streams — the burn does not reduce the validator's tip
        // (fixes Solana's error). The base fee is floored at 1 gwei so the
        // burn never dies at scale (fixes Ethereum's error).
        let block_gas_used: u64 = block.transactions.iter().map(|tx| tx.gas_limit).sum();
        let mut total_burned: u128 = 0;
        let mut total_tip: u128 = 0;
        for tx in &block.transactions {
            let (burn, tip) = self.fee_market.split_fee(tx.gas_price, tx.gas_limit);
            total_burned = total_burned.saturating_add(burn);
            total_tip = total_tip.saturating_add(tip);
        }
        tracing::info!(
            "EIP-1559 v3 block {}: gas_used={}, burned={} (base fee, floor={} gwei), validator_tip={} (separate stream)",
            block.header.height, block_gas_used,
            total_burned, self.fee_market.current_base_fee() / 1_000_000_000,
            total_tip,
        );
        // Adjust the base fee for the NEXT block based on this block's fullness.
        self.fee_market.update_after_block(block_gas_used);

        // Leader signs the block
        let block_hash = block.hash();
        let signature = self.keypair.sign(&block_hash);
        block.header.signature = signature;

        self.phase = BftPhase::Prepare;
        Ok(block)
    }

    /// Validator votes on a proposal (PREPARE phase).
    /// Verifies the block signature, header, and tx_root before voting.
    pub fn vote_prepare(&mut self, proposal: &Block) -> Result<BftVote, CoreError> {
        // Genesis block (height 0) is unsigned -- skip signature verification.
        // All other blocks must have a valid Dilithium3 signature.
        if proposal.header.height > 0 {
            proposal.verify_block_signature()?;
            // Forward security (anti long-range): the block's signer must be
            // an authorized key for the block's epoch. An attacker who bought
            // a retired epoch key cannot propose or vote on a new-epoch block.
            self.validate_forward_security(proposal.header.epoch, &proposal.header.validator)?;
            // PQ-VRF leader election: verify the leader's VRF proof. The leader
            // must have correctly evaluated VRF(secret, parent_hash || height)
            // and committed the output. A forged or invalid VRF is rejected --
            // only the secret key holder can produce a valid proof.
            let mut vrf_input = proposal.header.parent_hash.to_vec();
            vrf_input.extend_from_slice(&proposal.header.height.to_le_bytes());
            verify_vrf(
                &proposal.header.validator,
                &vrf_input,
                &VrfOutput(proposal.header.vrf_output),
                &VrfProof(proposal.header.vrf_proof.0),
            )
            .map_err(|_| CoreError::InvalidBlock(
                "VRF proof invalid: leader did not correctly evaluate the VRF".to_string(),
            ))?;
        }

        // Verify the proposal header
        if let Some(parent) = self.state.latest_block() {
            proposal.validate_header(parent)?;
        }

        // Verify tx_root
        proposal.validate_tx_root()?;

        // G14 — Forced-inclusion: validate that the block includes all
        // forced txs that fit in the gas budget. A block that censors a
        // forced tx is REJECTED — the proposer cannot skip a tx that the
        // committee forced.
        self.validate_forced_inclusion(proposal, 30_000_000, 21_000)?;

        let block_hash = proposal.hash();
        let vote = BftVote {
            block_hash,
            height: proposal.header.height,
            round: self.state.current_round,
            voter: self.keypair.public.clone(),
            signature: self.keypair.sign(&block_hash),
            phase: BftVotePhase::Prepare,
            hybrid_signature: None,
            hybrid_pubkey: None,
        };

        // Dedup: don't add our own vote twice. Re-proposes call this again,
        // and without dedup the leader's own vote accumulates -> votes.len()
        // falsely reaches supermajority with only duplicated self-votes.
        let votes = self.prepare_votes.entry(block_hash).or_default();
        if !votes.iter().any(|v| v.voter.0 == self.keypair.public.0) {
            votes.push(vote.clone());
        }

        Ok(vote)
    }

    /// Collect a PREPARE vote from another validator.
    /// Verifies the vote signature before counting it.
    pub fn collect_prepare_vote(&mut self, vote: BftVote) -> Result<bool, CoreError> {
        // Reject commit-phase votes in the prepare collector
        if vote.phase != BftVotePhase::Prepare {
            return Err(CoreError::Consensus("expected prepare-phase vote, got commit-phase".into()));
        }

        // Reject votes for already-finalized heights. A late PREPARE vote
        // arriving after the block was finalized would re-accumulate and
        // re-trigger supermajority, producing a redundant vote_commit() that
        // broadcasts a stale COMMIT vote -- which in turn makes peers re-attempt
        // finalize_block() on an already-committed height and log "height
        // mismatch" errors every block. Silently ignoring stale votes is
        // correct BFT behavior: the block is already committed.
        if vote.height <= self.state.last_finalized_height {
            return Ok(false);
        }

        // Verify voter is active
        let voter_active = self
            .state
            .validators
            .iter()
            .any(|v| v.pubkey.0 == vote.voter.0 && v.status == ValidatorStatus::Active);
        if !voter_active {
            return Err(CoreError::Consensus("prepare vote from non-active validator".into()));
        }

        // Verify the vote signature (PQ2: dual Dilithium3 + Ed25519 if present)
        vote.verify_vote_signature()
            .map_err(|_| CoreError::Consensus("invalid prepare vote signature".into()))?;

        // Equivocation detection (M2): if this voter already signed a DIFFERENT
        // block at the same height in PREPARE, it is double-signing. Slash and
        // reject the conflicting vote so two competing blocks can't both build
        // a quorum from the same validator. Run BEFORE the votes borrow so we
        // don't hold two mutable borrows of self at once.
        if self.detect_and_slash_equivocation(&vote.voter, vote.height, &vote.block_hash, BftVotePhase::Prepare) {
            return Err(CoreError::Equivocation(format!(
                "validator double-signed at height {} in prepare phase", vote.height
            )));
        }

        let votes = self.prepare_votes.entry(vote.block_hash).or_default();
        // Don't add duplicate votes
        if votes.iter().any(|v| v.voter.0 == vote.voter.0) {
            return Ok(false);
        }

        votes.push(vote);

        // Check if we have supermajority for PREPARE
        let count = votes.len();
        if self.state.has_supermajority(count) {
            self.phase = BftPhase::Commit;
            return Ok(true);
        }
        Ok(false)
    }

    /// Validator votes on a COMMIT certificate.
    pub fn vote_commit(&mut self, block_hash: [u8; 64], height: u64) -> Result<BftVote, CoreError> {
        let vote = BftVote {
            block_hash,
            height,
            round: self.state.current_round,
            voter: self.keypair.public.clone(),
            signature: self.keypair.sign(&block_hash),
            phase: BftVotePhase::Commit,
            hybrid_signature: None,
            hybrid_pubkey: None,
        };

        // Dedup: same rationale as vote_prepare -- prevents duplicated self-votes.
        let votes = self.commit_votes.entry(block_hash).or_default();
        if !votes.iter().any(|v| v.voter.0 == self.keypair.public.0) {
            votes.push(vote.clone());
        }

        Ok(vote)
    }

    /// Collect a COMMIT vote. Returns true if the block can be finalized.
    /// Verifies the vote signature before counting it.
    pub fn collect_commit_vote(&mut self, vote: BftVote) -> Result<bool, CoreError> {
        // Reject prepare-phase votes in the commit collector
        if vote.phase != BftVotePhase::Commit {
            return Err(CoreError::Consensus("expected commit-phase vote, got prepare-phase".into()));
        }

        // Reject votes for already-finalized heights. The 4th validator's
        // COMMIT vote (with 4 validators, threshold = 3) often arrives AFTER
        // the block is already finalized by the first 3. Without this guard,
        // the late vote re-triggers supermajority -> finalize_block() is called
        // again on the same height -> validate_header() sees the block is at
        // the same height as the now-finalized parent -> "height mismatch"
        // error logged every block. Silently ignoring is correct: the block
        // is already committed and finalized.
        if vote.height <= self.state.last_finalized_height {
            return Ok(false);
        }

        let voter_active = self
            .state
            .validators
            .iter()
            .any(|v| v.pubkey.0 == vote.voter.0 && v.status == ValidatorStatus::Active);
        if !voter_active {
            return Err(CoreError::Consensus("commit vote from non-active validator".into()));
        }

        // Verify the vote signature (PQ2: dual Dilithium3 + Ed25519 if present)
        vote.verify_vote_signature()
            .map_err(|_| CoreError::Consensus("invalid commit vote signature".into()))?;

        // Equivocation detection (M2): double-signing in COMMIT phase too.
        // Run BEFORE the votes borrow to avoid two mutable borrows of self.
        if self.detect_and_slash_equivocation(&vote.voter, vote.height, &vote.block_hash, BftVotePhase::Commit) {
            return Err(CoreError::Equivocation(format!(
                "validator double-signed at height {} in commit phase", vote.height
            )));
        }

        let votes = self.commit_votes.entry(vote.block_hash).or_default();
        if votes.iter().any(|v| v.voter.0 == vote.voter.0) {
            return Ok(false);
        }

        votes.push(vote);

        let count = votes.len();
        if self.state.has_supermajority(count) {
            self.phase = BftPhase::Finalize;
            return Ok(true);
        }
        Ok(false)
    }

    /// Finalize a block after COMMIT supermajority.
    pub fn finalize_block(&mut self, block: Block) -> Result<(), CoreError> {
        // MTP timestamp validation (#8): reject blocks whose timestamp is
        // more than 2h from the median of the last 11 blocks. This prevents
        // timejacking attacks where an attacker manipulates network time to
        // accept a fraudulent chain. The genesis block (height 0) is exempt.
        if block.header.height > 0 {
            self.state.validate_timestamp_mtp(&block)?;
        }

        self.state.finalize_block(block)?;

        // Clean up vote storage for finalized height
        let height = self.state.last_finalized_height;
        self.prepare_votes.retain(|_, votes| {
            votes.first().map(|v| v.height != height).unwrap_or(true)
        });
        self.commit_votes.retain(|_, votes| {
            votes.first().map(|v| v.height != height).unwrap_or(true)
        });

        self.phase = BftPhase::Propose;
        Ok(())
    }

    /// Get the current phase.
    pub fn current_phase(&self) -> BftPhase {
        self.phase
    }

    /// Check if this node is the leader for the current round.
    pub fn is_leader(&self) -> bool {
        match self.state.select_leader() {
            Some(leader) => leader.pubkey.0 == self.keypair.public.0,
            None => false,
        }
    }
}

/// Compute a Merkle root for a list of transactions.
fn compute_merkle_root(txs: &[Transaction]) -> [u8; 64] {
    if txs.is_empty() {
        return [0u8; 64];
    }
    let mut layer: Vec<[u8; 64]> = txs
        .iter()
        .map(|tx| tx.hash()) // Uses canonical encoding
        .collect();

    while layer.len() > 1 {
        let mut next = Vec::with_capacity((layer.len() + 1) / 2);
        for pair in layer.chunks(2) {
            let mut combined = [0u8; 128];
            combined[..64].copy_from_slice(&pair[0]);
            if pair.len() == 2 {
                combined[64..].copy_from_slice(&pair[1]);
            } else {
                combined[64..].copy_from_slice(&pair[0]);
            }
            next.push(keccak512(&combined));
        }
        layer = next;
    }
    layer[0]
}

/// Get the current timestamp in milliseconds since Unix epoch.
fn current_timestamp() -> u64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

