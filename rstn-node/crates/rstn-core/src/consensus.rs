#[cfg(test)]
mod tests {
    use super::*;
    use rstn_crypto::{Dilithium3Keypair, Dilithium3PublicKey, Dilithium3Signature, keccak512};

    fn make_validator(pubkey_byte: u8, stake: u128, status: ValidatorStatus) -> Validator {
        Validator {
            pubkey: Dilithium3PublicKey([pubkey_byte; 1952]),
            stake,
            commission: 5,
            shard_id: 0,
            uptime: 99.9,
            blocks_produced: 0,
            status,
        }
    }

    #[test]
    fn test_bft_phase_ordering() {
        assert!(BftPhase::Propose < BftPhase::Prepare);
        assert!(BftPhase::Prepare < BftPhase::Commit);
        assert!(BftPhase::Commit < BftPhase::Finalize);
    }

    #[test]
    fn test_supermajority_threshold() {
        let mut state = ConsensusState::new(4);
        state.validators = vec![
            make_validator(1, 1000, ValidatorStatus::Active),
            make_validator(2, 1000, ValidatorStatus::Active),
            make_validator(3, 1000, ValidatorStatus::Active),
            make_validator(4, 1000, ValidatorStatus::Active),
        ];

        // 4 active -> threshold = 4*2/3+1 = 3
        assert!(!state.has_supermajority(2));
        assert!(state.has_supermajority(3));
        assert!(state.has_supermajority(4));
    }

    #[test]
    fn test_slashed_validators_excluded_from_threshold() {
        let mut state = ConsensusState::new(4);
        state.validators = vec![
            make_validator(1, 1000, ValidatorStatus::Active),
            make_validator(2, 1000, ValidatorStatus::Active),
            make_validator(3, 1000, ValidatorStatus::Slashed),
            make_validator(4, 1000, ValidatorStatus::Active),
        ];

        // 3 active -> threshold = 3*2/3+1 = 3
        assert!(!state.has_supermajority(2));
        assert!(state.has_supermajority(3));
    }

    #[test]
    fn test_proportional_slashing() {
        let mut state = ConsensusState::new(1);
        state.validators = vec![make_validator(1, 1_000_000, ValidatorStatus::Active)];

        // Slash 5% for double-signing
        state.slash_validator(&Dilithium3PublicKey([1; 1952]), 5).unwrap();
        assert_eq!(state.validators[0].stake, 950_000);
        assert_eq!(state.validators[0].status, ValidatorStatus::Active); // <10% -> not slashed

        // Slash 10% of the REMAINING stake (950,000) -> 95,000 slashed -> 855,000.
        // Slashing is proportional to the current stake, not the original.
        state.slash_validator(&Dilithium3PublicKey([1; 1952]), 10).unwrap();
        assert_eq!(state.validators[0].stake, 855_000);
        assert_eq!(state.validators[0].status, ValidatorStatus::Slashed);
    }

    #[test]
    fn test_double_slash_rejected() {
        let mut state = ConsensusState::new(1);
        state.validators = vec![make_validator(1, 1_000_000, ValidatorStatus::Slashed)];

        let result = state.slash_validator(&Dilithium3PublicKey([1; 1952]), 5);
        assert!(result.is_err());
    }

    #[test]
    fn test_leader_selection_round_robin() {
        let mut state = ConsensusState::new(4);
        state.validators = vec![
            make_validator(1, 1000, ValidatorStatus::Active),
            make_validator(2, 1000, ValidatorStatus::Active),
            make_validator(3, 1000, ValidatorStatus::Inactive), // should be skipped
            make_validator(4, 1000, ValidatorStatus::Active),
        ];

        // Height 0, view 0 -> validator 1 (index 0 of active)
        state.last_finalized_height = 0;
        state.view_offset = 0;
        let leader = state.select_leader().unwrap();
        assert_eq!(leader.pubkey.0[0], 1);

        // Height 1 -> validator 2 (index 1 of active)
        state.last_finalized_height = 1;
        state.view_offset = 0;
        let leader = state.select_leader().unwrap();
        assert_eq!(leader.pubkey.0[0], 2);

        // Height 2 -> validator 4 (validator 3 is inactive, so index 2 of active)
        state.last_finalized_height = 2;
        state.view_offset = 0;
        let leader = state.select_leader().unwrap();
        assert_eq!(leader.pubkey.0[0], 4);

        // View-change at height 0: view_offset=1 skips validator 1 -> validator 2
        state.last_finalized_height = 0;
        state.view_offset = 1;
        let leader = state.select_leader().unwrap();
        assert_eq!(leader.pubkey.0[0], 2);
    }

    #[test]
    fn test_no_leader_when_all_inactive() {
        let mut state = ConsensusState::new(1);
        state.validators = vec![make_validator(1, 1000, ValidatorStatus::Inactive)];
        assert!(state.select_leader().is_none());
    }

    #[test]
    fn test_duplicate_vote_rejected() {
        let mut state = ConsensusState::new(1);
        state.validators = vec![make_validator(1, 1000, ValidatorStatus::Active)];

        let block_hash = keccak512(b"test block");
        let vote = BftVote {
            block_hash,
            height: 1,
            round: 0,
            voter: Dilithium3PublicKey([1; 1952]),
            signature: Dilithium3Signature([0u8; 3309]),
            phase: BftVotePhase::Prepare,
            hybrid_signature: None,
            hybrid_pubkey: None,
        };

        // First vote: signature verification will fail (fake sig), but we test the dup logic
        let result = state.add_vote(vote.clone());
        // Should fail because the signature is fake (all zeros)
        assert!(result.is_err());
    }
}
